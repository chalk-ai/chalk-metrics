use std::borrow::Cow;

/// A content-based name fingerprint computed at compile time by generated metrics.
/// The fields are private so callers cannot provide a hash inconsistent with the name.
#[doc(hidden)]
#[derive(Clone, Copy)]
pub struct MetricName {
    name: &'static str,
    hash: u64,
}

impl MetricName {
    pub const fn new(name: &'static str) -> Self {
        let bytes = name.as_bytes();
        let mut hash = 0u64;
        let mut index = 0;
        while index < bytes.len() {
            hash = hash.wrapping_mul(31).wrapping_add(bytes[index] as u64);
            index += 1;
        }
        Self { name, hash }
    }

    pub(crate) fn as_str(self) -> &'static str {
        self.name
    }

    pub(crate) fn hash(self) -> u64 {
        self.hash
    }
}

/// Support trait implemented by tag types generated by `define_tags!`.
#[doc(hidden)]
pub trait MetricTag {
    const EXPORT_NAME: &'static str;

    fn export_value(&self) -> Cow<'static, str>;

    /// The exported value without allocating. Equal to `export_value()`.
    fn value_str(&self) -> &str;
}

/// Support trait implemented by namespace marker types generated by
/// `define_namespaces!`.
#[doc(hidden)]
pub trait MetricNamespace {
    fn path() -> &'static [&'static str];
}

/// Marker namespace used for top-level metrics.
#[doc(hidden)]
pub struct NoNamespace;

impl MetricNamespace for NoNamespace {
    #[inline]
    fn path() -> &'static [&'static str] {
        &[]
    }
}
