use std::borrow::Cow;
use std::hash::BuildHasher;

/// Fixed seed so a tag set always hashes to the same value within and across runs.
const TAG_HASH_SEED: u64 = 0x6368_616c_6b5f_6d74;

/// Hasher used by generated metrics to fingerprint their tag values.
///
/// A wrapper whose methods are compiled once, here, rather than inlined into
/// every generated metric: inlining them made crates that define many metrics
/// much slower to compile in release builds.
#[doc(hidden)]
pub struct TagHasher(foldhash::quality::FoldHasher<'static>);

impl std::hash::Hasher for TagHasher {
    #[inline(never)]
    fn write(&mut self, bytes: &[u8]) {
        self.0.write(bytes);
    }

    #[inline(never)]
    fn write_u8(&mut self, value: u8) {
        self.0.write_u8(value);
    }

    #[inline(never)]
    fn write_u64(&mut self, value: u64) {
        self.0.write_u64(value);
    }

    #[inline(never)]
    fn write_usize(&mut self, value: usize) {
        self.0.write_usize(value);
    }

    #[inline(never)]
    fn finish(&self) -> u64 {
        self.0.finish()
    }
}

/// A fresh [`TagHasher`] with the fixed seed.
#[doc(hidden)]
#[inline(never)]
pub fn tag_hasher() -> TagHasher {
    TagHasher(foldhash::quality::FixedState::with_seed(TAG_HASH_SEED).build_hasher())
}

/// Whether `stored` (the tags of an existing series) holds exactly the keys and
/// values in `mine`, in order, skipping entries of `mine` whose value is `None`
/// (an optional tag that is not set). One shared function, so generated metrics
/// only build the small `mine` array.
#[doc(hidden)]
pub fn tags_match(
    stored: &[(&'static str, Cow<'static, str>)],
    mine: &[(&'static str, Option<&str>)],
) -> bool {
    let mut stored = stored.iter();
    for (key, value) in mine {
        let Some(value) = value else {
            continue;
        };
        match stored.next() {
            Some((stored_key, stored_value)) if stored_key == key && stored_value == value => {}
            _ => return false,
        }
    }
    stored.next().is_none()
}

/// A content-based name fingerprint computed at compile time by generated metrics.
/// The fields are private so callers cannot provide a hash inconsistent with the name.
#[doc(hidden)]
#[derive(Clone, Copy)]
pub struct MetricName {
    name: &'static str,
    hash: u64,
}

impl MetricName {
    pub const fn new(name: &'static str) -> Self {
        let bytes = name.as_bytes();
        let mut hash = 0u64;
        let mut index = 0;
        while index < bytes.len() {
            hash = hash.wrapping_mul(31).wrapping_add(bytes[index] as u64);
            index += 1;
        }
        Self { name, hash }
    }

    pub(crate) fn as_str(self) -> &'static str {
        self.name
    }

    pub(crate) fn hash(self) -> u64 {
        self.hash
    }
}

/// Support trait implemented by tag types generated by `define_tags!`.
#[doc(hidden)]
pub trait MetricTag {
    const EXPORT_NAME: &'static str;

    /// The borrowed form used by a metric's `Ref` struct: `&'a str` for string
    /// tags, `Self` for enum tags.
    type Ref<'a>: TagRef
    where
        Self: 'a;

    fn export_value(&self) -> Cow<'static, str>;

    /// The exported value without allocating. Equal to `export_value()`.
    fn value_str(&self) -> &str;

    /// This tag as its borrowed form. Hashes and compares like `self`.
    fn tag_ref(&self) -> Self::Ref<'_>;
}

/// Borrowed tag values held by generated `Ref` structs.
///
/// Hashing must feed the hasher the same bytes as the owned tag's `Hash`, so an
/// owned and a borrowed record with equal values share one series.
#[doc(hidden)]
pub trait TagRef: Copy + std::hash::Hash + std::fmt::Debug {
    /// The exported value without allocating.
    fn value_str(&self) -> &str;

    /// The exported value as stored on first insert.
    fn export_value(&self) -> Cow<'static, str>;
}

impl TagRef for &str {
    #[inline]
    fn value_str(&self) -> &str {
        self
    }

    fn export_value(&self) -> Cow<'static, str> {
        Cow::Owned((*self).to_owned())
    }
}

/// Support trait implemented by namespace marker types generated by
/// `define_namespaces!`.
#[doc(hidden)]
pub trait MetricNamespace {
    fn path() -> &'static [&'static str];
}

/// Marker namespace used for top-level metrics.
#[doc(hidden)]
pub struct NoNamespace;

impl MetricNamespace for NoNamespace {
    #[inline]
    fn path() -> &'static [&'static str] {
        &[]
    }
}
